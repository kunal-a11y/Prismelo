import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function collectMarkdown(directory) {
  if (!fs.existsSync(directory)) return {};
  const files = {};

  function visit(current) {
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      const absolute = path.join(current, entry.name);
      if (entry.isDirectory()) {
        visit(absolute);
      } else if (entry.isFile() && entry.name.endsWith(".mdx")) {
        const relative = path.relative(directory, absolute).replaceAll("\\", "/");
        const key = relative.slice(0, -".mdx".length);
        if (!entry.name.startsWith("_")) {
          files[key] = fs.readFileSync(absolute, "utf8");
        }
      }
    }
  }

  visit(directory);
  return Object.fromEntries(Object.entries(files).sort(([a], [b]) => a.localeCompare(b)));
}

const docs = collectMarkdown(path.join(root, "content", "docs"));
const resources = collectMarkdown(path.join(root, "content", "resources"));
const output = `// Generated by scripts/generate-content.mjs before each production build.\n` +
  `export const DOC_FILES: Record<string, string> = ${JSON.stringify(docs, null, 2)};\n\n` +
  `export const RESOURCE_FILES: Record<string, string> = ${JSON.stringify(resources, null, 2)};\n`;

fs.writeFileSync(path.join(root, "lib", "generated-content.ts"), output);
