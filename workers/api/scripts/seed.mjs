#!/usr/bin/env node
/**
 * Turns content/resources/*.mdx into seed.sql for D1.
 *
 * The site's posts lived as files. D1 needs rows, so this reads the same files
 * once and writes the INSERTs. Re-running is safe: existing rows are left alone
 * (`ON CONFLICT DO NOTHING`), so edits made in the admin area are never
 * overwritten by a stale file.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const resourcesDir = path.resolve(here, "../../../content/resources");
const output = path.resolve(here, "../seed.sql");

/** Frontmatter is a flat YAML map here, so a tiny parser beats a dependency. */
function parseFrontmatter(raw) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(raw);
  if (!match) return { data: {}, body: raw };

  const data = {};
  for (const line of match[1].split(/\r?\n/)) {
    const field = /^([A-Za-z_][\w-]*):\s*(.*)$/.exec(line);
    if (!field) continue;
    let value = field[2].trim().replace(/^["']|["']$/g, "");
    if (value === "true") value = true;
    else if (value === "false") value = false;
    data[field[1]] = value;
  }

  return { data, body: match[2].trim() };
}

const quote = (value) => `'${String(value).replace(/'/g, "''")}'`;

if (!fs.existsSync(resourcesDir)) {
  console.error(`No posts found at ${resourcesDir}`);
  process.exit(1);
}

const files = fs
  .readdirSync(resourcesDir)
  .filter((file) => file.endsWith(".mdx") && !file.startsWith("_"));

const statements = [
  "-- Generated by scripts/seed.mjs from content/resources/*.mdx",
  "-- Safe to re-run: existing slugs are not modified.",
];

for (const file of files) {
  const slug = file.replace(/\.mdx$/, "");
  const { data, body } = parseFrontmatter(fs.readFileSync(path.join(resourcesDir, file), "utf8"));
  const date =
    data.date instanceof Date ? data.date.toISOString().slice(0, 10) : String(data.date ?? new Date().toISOString().slice(0, 10));

  statements.push(
    `INSERT INTO posts (slug, title, description, category, published_at, featured, draft, body, updated_at)
VALUES (${quote(slug)}, ${quote(data.title ?? slug)}, ${quote(data.description ?? "")}, ${quote(
      data.category ?? "Engineering",
    )}, ${quote(date.slice(0, 10))}, ${data.featured ? 1 : 0}, 0, ${quote(body)}, ${quote(new Date().toISOString())})
ON CONFLICT(slug) DO NOTHING;`,
  );
}

fs.writeFileSync(output, `${statements.join("\n\n")}\n`);
console.log(`Wrote ${output} (${files.length} posts)`);
